def guide_body(bot_mention: str) -> str:
    return f"""やあ!このチャンネルの質問対応 Bot だよ。困ったときに呼んでね。

## 呼び方

**質問ごとに新しい投稿を作って**、その中で {bot_mention} を付けて話しかけてね。

**1つの投稿では1つの質問**にしてもらえると助かる!
1つの投稿の中で話題が変わると、こっちが前の話と混ぜちゃって的外れな答えになるんだ。

## 答えられること

- **環境構築** — VSCode、Git、Node.js の導入でつまずいたとき
- **GitHub** — clone / commit / push、ブランチ、コンフリクトの直し方
- **設定ファイル** — `package.json`、`.gitignore`、`.env` って何?どう書くの?
- **このハッカソンのこと** — スケジュール、評価軸、提出方法、会場のこと

## 答えられないこと

- プロダクトのコードの実装やデバッグ
- ライブラリや API の使い方
- 技術選定の相談

これらは ChatGPT や Claude みたいな外部の AI のほうが得意なんだ。
聞いてくれれば、**そのままコピーして外部 AI に投げられる質問文**を作って渡すよ。
初心者のうちは「AI への聞き方」が一番むずかしいから、そこは任せて!

## スクショ歓迎

エラーが出たら、**ターミナルの画面をそのまま撮って貼ってOK**。
文字に起こさなくていいし、こっちで読むよ。OS も画面から判断できることが多い。

## 解決しなかったら

回答の下に出る **「解決しなかった」ボタン**を押してね。
エンジニアメンターにここまでのやり取りをまとめて渡して、人を呼ぶよ。
遠慮しなくていいから、詰まったらすぐ押して!"""


