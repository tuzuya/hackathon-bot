"""参加者・メンターに表示される文言をまとめたモジュール。

トーンの調整を後からまとめてやれるように、文言をコード中に散らさない
(CLAUDE.md「コードスタイル」)。
口調は SPEC §6.1 のトーン規定に従い、フレンドリーな友達口調で統一する。
"""

from __future__ import annotations

# --- 受付を知らせるリアクション ------------------------------------------
# LLM の応答には数秒〜数十秒かかる。無反応だと初心者は「壊れた?」と何度も送るため、
# 受け取った合図を必ず出す(CLAUDE.md「応答体験」)。
#
# typing 表示ではなくリアクションを使う理由:
#   typing は 5 秒ごとに API を叩き続ける必要があり、実際に Discord 側の
#   レート制限(429 / error 40062)に当たって回答が止まった。
#   リアクションは 1 回の API 呼び出しで済み、回答が出るまで表示が消えない。
RECEIVED_REACTION = "👀"

# --- 動作範囲の案内(SPEC §3.3)-------------------------------------------
# 相談室フォーラムの外でメンションされたとき。LLM は呼ばない。
#
# ⚠️ フォーラム名は必ず設定(FORUM_CHANNEL_NAME)から受け取ること。
#    ここに名前を直接書くと、チャンネル名を変えたときに案内文だけ古いまま残り、
#    参加者が存在しないチャンネルを探すことになる。
def out_of_scope_guide(forum_name: str) -> str:
    return (
        "ここでは答えられないんだ、ごめんね!\n"
        f"質問はチームの **「{forum_name}」** に新しい投稿を作って、"
        "そこで呼んでくれると答えられるよ〜\n"
        "投稿は「1つの投稿につき1つの質問」にしておくと、話が混ざらなくておすすめ!"
    )


# フォーラムチャンネル自体に直接メンションが来たとき(投稿の中ではない場合)。
def forum_root_guide(forum_name: str) -> str:
    return (
        f"「{forum_name}」の中に **新しい投稿を作って**、その中で呼んでね!\n"
        "投稿ごとに会話を分けておくと、後から見返しやすいよ〜"
    )

# --- 段階1のダミー応答(段階2で LLM 応答に置き換える)---------------------
STAGE1_PLACEHOLDER = (
    "呼んでくれてありがとう!接続テストは成功してるよ〜\n"
    "まだ中身を準備してるところだから、質問への回答はもう少し待っててね!"
)

# --- エラー時(無言で落ちないこと。CLAUDE.md「エラー処理」)----------------
LLM_ERROR = (
    "ごめん、今ちょっと調子が悪いみたい…!\n"
    "少し時間をおいてもう一度呼んでみて。それでもダメならメンターに声をかけてね。"
)

