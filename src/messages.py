# ============================================================
# エスカレーション(SPEC §5)
# ============================================================
#
# ⚠️ 通知本文は必ずこの固定テンプレートから組み立てる(CLAUDE.md 制約 1)。
#    LLM が生成した要約を本文(content)に入れてはいけない。
#    要約は embed に入れる。embed の中身はメンションとして解決されないため、
#    万一「@メンター」という文字列が紛れ込んでも通知は飛ばない。

# 「解決しなかった」ボタンのラベル。SPEC §5.1 より、回答の文章では触れない。
UNRESOLVED_BUTTON_LABEL = "解決しなかった"
CLAIM_BUTTON_LABEL = "対応する"
COMPLETE_BUTTON_LABEL = "完了"


def escalation_notice(role_id: int) -> str:
    """投稿内に出すメンター呼び出し本文。

    SPEC §5.1 より、チーム名・ユーザー名・投稿リンクは入れない(その場で見えるため)。
    """
    return f"<@&{role_id}> 解決しなかったみたい。対応をお願いします。"


